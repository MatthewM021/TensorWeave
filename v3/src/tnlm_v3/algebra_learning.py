@dataclass(frozen=True)
class HypothesisLearnability:
    hypothesis: LearningHypothesis
    parameter_count: int
    constraint_rank: int
    nullity: int
    heldout_behavior_identified_conditionally: bool
    canonical_state_supervision_assumed: bool
    universal_law_supplied: bool
    sharing_law_selected_from_data: bool

    def __post_init__(self) -> None:
        if type(self.hypothesis) is not LearningHypothesis:
            raise TypeError("hypothesis must be exact LearningHypothesis")
        for name in ("parameter_count", "constraint_rank", "nullity"):
            value = getattr(self, name)
            if type(value) is not int:
                raise TypeError(f"{name} must be an exact integer")
            if value < 0:
                raise ValueError(f"{name} must be nonnegative")
        if self.constraint_rank + self.nullity != self.parameter_count:
            raise ValueError("constraint rank and nullity must partition parameters")
        for name in (
            "heldout_behavior_identified_conditionally",
            "canonical_state_supervision_assumed",
            "universal_law_supplied",
            "sharing_law_selected_from_data",
        ):
            if type(getattr(self, name)) is not bool:
                raise TypeError(f"{name} must be an exact boolean")
        if self.heldout_behavior_identified_conditionally != (self.nullity == 0):
            raise ValueError("conditional identification disagrees with nullity")
        if not self.canonical_state_supervision_assumed:
            raise ValueError("hypothesis certificate assumes canonical-state supervision")
        if self.sharing_law_selected_from_data:
            raise ValueError("hypothesis certificate does not select the sharing law")


@dataclass(frozen=True)
class PrototypeCell:
    """One column of a shared value-block operator."""

    family: str
    transform: int | None
    source_value: int

    def __post_init__(self) -> None:
        if type(self.family) is not str or self.family not in {
            "bind",
            "update",
            "copy",
            "query",
        }:
            raise ValueError("unknown shared prototype family")
        if self.transform is not None and type(self.transform) is not int:
            raise TypeError("transform must be an exact integer or None")
        if type(self.source_value) is not int:
            raise TypeError("source_value must be an exact integer")
        if self.source_value < 0:
            raise ValueError("source_value must be nonnegative")
        if self.family == "update":
            if self.transform is None or self.transform < 0:
                raise ValueError("update cells require a nonnegative transform")
        elif self.transform is not None:
            raise ValueError("only update cells may carry a transform")

    @property
    def label(self) -> str:
        if self.family == "update":
            return f"update:{self.transform}:source:{self.source_value}"
        return f"{self.family}:source:{self.source_value}"


@dataclass(frozen=True)
class SharedPrototypeCoverage:
    """Exact design-rank certificate for one generated seen-only sample."""

    schema: str
    task_fingerprint: str
    split: SeenSplit
    seed: int
    document_count: int
    document_length: int
    event_count: int
    parameter_count: int
    design_rank: int
    nullity: int
    observed_cell_count: int
    total_cell_count: int
    cell_observation_counts: tuple[tuple[str, int], ...]
    cell_event_locations: tuple[tuple[str, int, str, int, int, int, int], ...]
    missing_cells: tuple[str, ...]
    smallest_nonzero_singular_value: float
    largest_singular_value: float
    condition_number: float
    full_rank: bool
    canonical_state_supervision_assumed: bool
    used_heldout_labels_for_fit: bool
    used_heldout_labels_for_selection: bool
    sample_sha256: str

    def __post_init__(self) -> None:
        if self.schema != "tnlm-v3-shared-prototype-coverage-v1":
            raise ValueError("unknown shared-prototype coverage schema")
        _require_sha256("task_fingerprint", self.task_fingerprint)
        _require_sha256("sample_sha256", self.sample_sha256)
        if self.split not in _SEEN_SPLITS:
            raise ValueError("coverage split must be train or validation")
        for name, minimum in (
            ("seed", 0),
            ("document_count", 1),
            ("document_length", 1),
            ("event_count", 1),
            ("parameter_count", 1),
            ("design_rank", 0),
            ("nullity", 0),
            ("observed_cell_count", 1),
            ("total_cell_count", 1),
        ):
            value = getattr(self, name)
            if type(value) is not int:
                raise TypeError(f"{name} must be an exact integer")
            if value < minimum:
                raise ValueError(f"{name} must be at least {minimum}")
        if self.event_count != self.document_count * self.document_length:
            raise ValueError("event count must equal documents times length")
        if self.design_rank + self.nullity != self.parameter_count:
            raise ValueError("design rank and nullity must partition parameters")
        for name in (
            "full_rank",
            "canonical_state_supervision_assumed",
            "used_heldout_labels_for_fit",
            "used_heldout_labels_for_selection",
        ):
            if type(getattr(self, name)) is not bool:
                raise TypeError(f"{name} must be an exact boolean")
        if self.full_rank != (self.design_rank == self.parameter_count):
            raise ValueError("full_rank disagrees with the design rank")
        if not self.canonical_state_supervision_assumed:
            raise ValueError("coverage must declare canonical-state supervision")
        if not isinstance(self.cell_observation_counts, tuple) or not (
            self.cell_observation_counts
        ):
            raise TypeError("cell observation counts must be a nonempty tuple")
        labels: list[str] = []
        for row in self.cell_observation_counts:
            if not isinstance(row, tuple) or len(row) != 2:
                raise TypeError("cell observation counts must be pairs")
            label, count = row
            if type(label) is not str or not label:
                raise ValueError("prototype labels must be nonempty exact strings")
            if type(count) is not int:
                raise TypeError("prototype counts must be exact integers")
            if count < 0:
                raise ValueError("prototype counts must be nonnegative")
            labels.append(label)
        if len(labels) != len(set(labels)):
            raise ValueError("prototype labels must be unique")
        if len(labels) != self.total_cell_count:
            raise ValueError("cell inventory does not match total_cell_count")
        if not isinstance(self.missing_cells, tuple) or any(
            type(label) is not str for label in self.missing_cells
        ):
            raise TypeError("missing_cells must be a tuple of exact strings")
        expected_missing = tuple(
            label for label, count in self.cell_observation_counts if count == 0
        )
        if self.missing_cells != expected_missing:
            raise ValueError("missing cells do not match zero-count cells")
        expected_observed = sum(
            count > 0 for _, count in self.cell_observation_counts
        )
        if self.observed_cell_count != expected_observed:
            raise ValueError("observed_cell_count disagrees with cell counts")
        if self.observed_cell_count + len(self.missing_cells) != self.total_cell_count:
            raise ValueError("observed and missing cells must partition the design")
        if self.parameter_count % self.total_cell_count:
            raise ValueError("parameter count must have a fixed per-cell width")
        cell_width = self.parameter_count // self.total_cell_count
        if self.design_rank != self.observed_cell_count * cell_width:
            raise ValueError("design rank disagrees with observed prototype cells")
        if not isinstance(self.cell_event_locations, tuple):
            raise TypeError("cell event locations must be an exact tuple")
        if len(self.cell_event_locations) != sum(
            count for _, count in self.cell_observation_counts
        ):
            raise ValueError("cell event locations must match observation counts")
        location_counts = {label: 0 for label, _ in self.cell_observation_counts}
        seen_locations: set[tuple[str, int]] = set()
        for row in self.cell_event_locations:
            if not isinstance(row, tuple) or len(row) != 7:
                raise TypeError("cell event locations must be seven-field tuples")
            document_id, event_index, label, *action_fields = row
            if type(document_id) is not str or not document_id:
                raise ValueError("event location document ID must be nonempty")
            if type(event_index) is not int or event_index < 0:
                raise ValueError("event location index must be nonnegative")
            if label not in location_counts:
                raise ValueError("event location names an unknown prototype cell")
            if any(type(value) is not int for value in action_fields):
                raise TypeError("event action fields must be exact integers")
            location = (document_id, event_index)
            if location in seen_locations:
                raise ValueError("event locations must be unique")
            seen_locations.add(location)
            location_counts[label] += 1
        if tuple(location_counts.items()) != self.cell_observation_counts:
            raise ValueError("event locations do not reproduce cell counts")
        if self.used_heldout_labels_for_fit or self.used_heldout_labels_for_selection:
            raise ValueError("seen-only coverage cannot use held-out labels")
        for value in (
            self.smallest_nonzero_singular_value,
            self.largest_singular_value,
            self.condition_number,
        ):
            if type(value) is not float or not math.isfinite(value) or value <= 0.0:
                raise ValueError("singular-value summaries must be positive finite floats")
        if self.smallest_nonzero_singular_value > self.largest_singular_value:
            raise ValueError("singular-value extrema are reversed")
        positive_counts = tuple(
            count for _, count in self.cell_observation_counts if count > 0
        )
        if (
            self.smallest_nonzero_singular_value
            != math.sqrt(float(min(positive_counts)))
            or self.largest_singular_value
            != math.sqrt(float(max(positive_counts)))
        ):
            raise ValueError("singular values disagree with cell observation counts")
        if self.condition_number != (
            self.largest_singular_value / self.smallest_nonzero_singular_value
        ):
            raise ValueError("condition number disagrees with singular values")


@dataclass(frozen=True)
class SharedPrototypeCoverageSweep:
    schema: str
    task_fingerprint: str
    split: SeenSplit
    document_count: int
    document_length: int
    seeds: tuple[int, ...]
    full_rank_count: int
    minimum_rank: int
    maximum_rank: int
    mean_rank: float
    results: tuple[SharedPrototypeCoverage, ...]

    def __post_init__(self) -> None:
        if self.schema != "tnlm-v3-shared-prototype-coverage-sweep-v1":
            raise ValueError("unknown coverage-sweep schema")
        _require_sha256("task_fingerprint", self.task_fingerprint)
        if self.split not in _SEEN_SPLITS:
            raise ValueError("coverage sweep split must be train or validation")
        for name, minimum in (
            ("document_count", 1),
            ("document_length", 1),
            ("full_rank_count", 0),
            ("minimum_rank", 0),
            ("maximum_rank", 0),
        ):
            value = getattr(self, name)
            if type(value) is not int:
                raise TypeError(f"{name} must be an exact integer")
            if value < minimum:
                raise ValueError(f"{name} must be at least {minimum}")
        if not isinstance(self.seeds, tuple) or any(
            type(seed) is not int or seed < 0 for seed in self.seeds
        ):
            raise TypeError("seeds must be a tuple of nonnegative exact integers")
        if len(self.seeds) != len(set(self.seeds)):
            raise ValueError("coverage sweep seeds must be unique")
        if not isinstance(self.results, tuple) or any(
            type(result) is not SharedPrototypeCoverage for result in self.results
        ):
            raise TypeError("results must be a tuple of exact coverage records")
        if not self.seeds or len(self.results) != len(self.seeds):
            raise ValueError("one coverage result is required per seed")
        if tuple(result.seed for result in self.results) != self.seeds:
            raise ValueError("coverage results must follow seed order")
        for result in self.results:
            if result.task_fingerprint != self.task_fingerprint:
                raise ValueError("coverage result task_fingerprint disagrees with sweep")
            if result.split != self.split:
                raise ValueError("coverage result split disagrees with sweep")
            if result.document_count != self.document_count:
                raise ValueError("coverage result document_count disagrees with sweep")
            if result.document_length != self.document_length:
                raise ValueError("coverage result document_length disagrees with sweep")
        if self.full_rank_count != sum(result.full_rank for result in self.results):
            raise ValueError("full-rank count is inconsistent")
        ranks = tuple(result.design_rank for result in self.results)
        if (self.minimum_rank, self.maximum_rank) != (min(ranks), max(ranks)):
            raise ValueError("rank extrema are inconsistent")
        if type(self.mean_rank) is not float or not math.isfinite(self.mean_rank):
            raise ValueError("mean rank must be a finite exact float")
        if self.mean_rank != float(sum(ranks) / len(ranks)):
            raise ValueError("mean rank is inconsistent")


