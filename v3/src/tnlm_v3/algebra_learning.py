"""Leakage-aware learnability certificates for the exact binding algebra.

This module deliberately separates three claims:

* exact passive identifiability on the declared train support;
* finite-sample excitation of a *supplied* shared-prototype model; and
* automatic selection of the sharing law.

Only the first two are computed here.  The finite-sample calculation replays
the exact canonical semantic state and is therefore an oracle-state system-
identification control, not a sequence-only representation-learning result.
The sealed held-out combination is never generated by the accepted splits.
"""

