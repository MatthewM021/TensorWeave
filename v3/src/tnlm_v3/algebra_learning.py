def analyze_algebra_learnability(
    config: ConfigLike,
    *,
    max_states: int = 1_000_000,
    max_permutations: int = 100_000,
) -> AlgebraLearnabilityReport:
    """Return the exact passive and conditional learnability boundary."""

    spec = _spec(config)
    identification = analyze_heldout_identification(
        spec,
        max_states=max_states,
        max_permutations=max_permutations,
    )
    folds = pseudoheldout_fold_certificates(spec)
    fields = {
        "schema": "tnlm-v3-algebra-learnability-v1",
        "task_fingerprint": _task_fingerprint(config),
        "heldout_pair": identification.heldout_pair,
        "full_state_count": identification.full_state_count,
        "train_state_count": identification.train_state_count,
        "full_feature_rank": identification.full_feature_rank,
        "train_feature_rank": identification.train_feature_rank,
        "passive_unrestricted_nullity": (
            identification.unrestricted_system.total_nullity
        ),
        "passive_uniform_recovery_possible": False,
        "zero_support_identical_likelihood_witness_exists": True,
        "one_separating_membership_probe": (
            f"BIND({identification.heldout_pair[0]},{identification.heldout_pair[1]})",
            f"QUERY({identification.heldout_pair[0]})",
        ),
        "hypotheses": _hypothesis_rows(identification),
        "pseudoheldout_folds": folds,
        "automatic_hypothesis_selection_performed": False,
        "sequence_only_representation_learning_performed": False,
    }
    payload = _report_payload(SimpleNamespace(**fields))
    digest = hashlib.sha256(
        json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()
    return AlgebraLearnabilityReport(**fields, report_sha256=digest)


