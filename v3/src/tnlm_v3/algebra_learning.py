@dataclass(frozen=True)
class LearnedSharedPrototypeTransducer:
    """Tables fit under supplied canonical state and universal key sharing."""

    schema: str
    task_fingerprint: str
    value_cardinality: int
    cell_outputs: tuple[tuple[str, tuple[int, ...] | None], ...]
    coverage: SharedPrototypeCoverage
    observation_sha256: str
    supervision_source: CanonicalSupervisionSource
    canonical_state_supervision_assumed: bool
    universal_key_sharing_supplied: bool
    cyclic_law_supplied: bool
    used_heldout_labels_for_fit: bool
    automatic_hypothesis_selection_performed: bool

    def __post_init__(self) -> None:
        if self.schema != "tnlm-v3-learned-shared-prototype-transducer-v1":
            raise ValueError("unknown learned-prototype schema")
        if type(self.value_cardinality) is not int or self.value_cardinality < 2:
            raise ValueError("value_cardinality must be an exact integer at least two")
        if not isinstance(self.cell_outputs, tuple):
            raise TypeError("cell_outputs must be an exact tuple")
        for row in self.cell_outputs:
            if not isinstance(row, tuple) or len(row) != 2:
                raise TypeError("cell_outputs rows must be exact pairs")
            label, output = row
            if type(label) is not str or not label:
                raise ValueError("cell output labels must be nonempty exact strings")
            if output is not None and not isinstance(output, tuple):
                raise TypeError("prototype outputs must be exact tuples or None")
        labels = tuple(label for label, _ in self.cell_outputs)
        if len(labels) != len(set(labels)):
            raise ValueError("prototype output labels must be unique")
        if type(self.coverage) is not SharedPrototypeCoverage:
            raise TypeError("coverage must be exact SharedPrototypeCoverage")
        if self.task_fingerprint != self.coverage.task_fingerprint:
            raise ValueError("model and coverage task fingerprints must match")
        coverage_labels = tuple(
            label for label, _ in self.coverage.cell_observation_counts
        )
        if labels != coverage_labels:
            raise ValueError("model and coverage cell inventories must match")
        if len(labels) * self.value_cardinality != self.coverage.parameter_count:
            raise ValueError("model width does not match the coverage parameter count")
        missing_outputs = {
            label for label, output in self.cell_outputs if output is None
        }
        if missing_outputs != set(self.coverage.missing_cells):
            raise ValueError("model missing outputs must exactly match coverage")
        if (
            type(self.observation_sha256) is not str
            or len(self.observation_sha256) != 64
            or any(character not in "0123456789abcdef" for character in self.observation_sha256)
        ):
            raise ValueError("observation_sha256 must be lowercase SHA-256")
        for _, output in self.cell_outputs:
            if output is not None:
                if len(output) != self.value_cardinality:
                    raise ValueError("prototype output width is inconsistent")
                if any(type(value) is not int for value in output):
                    raise TypeError("prototype outputs must be exact integers")
                if any(value not in (0, 1) for value in output) or sum(output) != 1:
                    raise ValueError("prototype outputs must be one-hot")
        for name in (
            "canonical_state_supervision_assumed",
            "universal_key_sharing_supplied",
            "cyclic_law_supplied",
            "used_heldout_labels_for_fit",
            "automatic_hypothesis_selection_performed",
        ):
            if type(getattr(self, name)) is not bool:
                raise TypeError(f"{name} must be an exact boolean")
        if not self.canonical_state_supervision_assumed:
            raise ValueError("this learner is explicitly canonical-state supervised")
        if type(self.supervision_source) is not CanonicalSupervisionSource:
            raise TypeError("supervision_source must be exact CanonicalSupervisionSource")
        if not self.universal_key_sharing_supplied:
            raise ValueError("this learner explicitly supplies universal key sharing")
        if self.cyclic_law_supplied:
            raise ValueError("the shared-prototype learner must fit, not supply, C_V")
        if self.used_heldout_labels_for_fit:
            raise ValueError("the shared-prototype learner is seen-only")
        if self.automatic_hypothesis_selection_performed:
            raise ValueError("the shared-prototype learner does not select sharing")


@dataclass(frozen=True)
class SharedPrototypeFitEvaluation:
    schema: str
    evaluated_cell_count: int
    exact_cell_count: int
    missing_cell_count: int
    all_value_tables_exact: bool
    all_valid_programs_exact_given_supplied_state_contract: bool
    heldout_semantics_used_only_for_postfit_evaluation: bool

    def __post_init__(self) -> None:
        if self.schema != "tnlm-v3-shared-prototype-fit-evaluation-v1":
            raise ValueError("unknown prototype-fit evaluation schema")
        for name in (
            "evaluated_cell_count",
            "exact_cell_count",
            "missing_cell_count",
        ):
            value = getattr(self, name)
            if type(value) is not int:
                raise TypeError(f"{name} must be an exact integer")
            if value < 0:
                raise ValueError(f"{name} must be nonnegative")
        for name in (
            "all_value_tables_exact",
            "all_valid_programs_exact_given_supplied_state_contract",
            "heldout_semantics_used_only_for_postfit_evaluation",
        ):
            if type(getattr(self, name)) is not bool:
                raise TypeError(f"{name} must be an exact boolean")
        if self.exact_cell_count + self.missing_cell_count > self.evaluated_cell_count:
            raise ValueError("prototype-fit counts are inconsistent")
        if self.all_value_tables_exact != (
            self.exact_cell_count == self.evaluated_cell_count
        ):
            raise ValueError("all_value_tables_exact is inconsistent")
        if self.all_valid_programs_exact_given_supplied_state_contract != (
            self.all_value_tables_exact
        ):
            raise ValueError("program exactness must follow exact closed tables")
        if not self.heldout_semantics_used_only_for_postfit_evaluation:
            raise ValueError("postfit evaluation must be explicitly labelled")


@dataclass(frozen=True)
class PseudoheldoutFoldCertificate:
    real_heldout_pair: tuple[int, int]
    pseudoheldout_pair: tuple[int, int]
    supplied_shared_parameter_count: int
    supplied_shared_design_rank: int
    supplied_shared_nullity: int
    supplied_shared_identifies_pseudoheldout: bool
    automatic_hypothesis_selection_performed: bool

    def __post_init__(self) -> None:
        for name in ("real_heldout_pair", "pseudoheldout_pair"):
            pair = getattr(self, name)
            if (
                not isinstance(pair, tuple)
                or len(pair) != 2
                or any(type(value) is not int or value < 0 for value in pair)
            ):
                raise ValueError(f"{name} must be a pair of nonnegative exact integers")
        if self.real_heldout_pair == self.pseudoheldout_pair:
            raise ValueError("pseudoheldout pair must differ from the real heldout pair")
        for name in (
            "supplied_shared_parameter_count",
            "supplied_shared_design_rank",
            "supplied_shared_nullity",
        ):
            value = getattr(self, name)
            if type(value) is not int:
                raise TypeError(f"{name} must be an exact integer")
            if value < 0:
                raise ValueError(f"{name} must be nonnegative")
        if self.supplied_shared_parameter_count == 0:
            raise ValueError("pseudoheldout parameter count must be positive")
        for name in (
            "supplied_shared_identifies_pseudoheldout",
            "automatic_hypothesis_selection_performed",
        ):
            if type(getattr(self, name)) is not bool:
                raise TypeError(f"{name} must be an exact boolean")
        if self.supplied_shared_design_rank + self.supplied_shared_nullity != (
            self.supplied_shared_parameter_count
        ):
            raise ValueError("pseudoheldout rank and nullity are inconsistent")
        if self.supplied_shared_identifies_pseudoheldout != (
            self.supplied_shared_nullity == 0
        ):
            raise ValueError("pseudoheldout identification disagrees with nullity")
        if self.automatic_hypothesis_selection_performed:
            raise ValueError("this certificate does not perform hypothesis selection")


